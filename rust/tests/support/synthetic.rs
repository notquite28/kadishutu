pub fn valid_pc_profile() -> Vec<u8> {
    let mut bytes = vec![0_u8; SAVE_LENGTH];
    bytes[0x40..0x44].copy_from_slice(b"GVAS");
    put_u32(&mut bytes, 0x44, 2);
    put_u32(&mut bytes, 0x48, 522);
    put_u16(&mut bytes, 0x4c, 4);
    put_u16(&mut bytes, 0x4e, 27);
    put_u16(&mut bytes, 0x50, 2);
    put_u32(&mut bytes, 0x52, 0);
    let branch_end = put_utf8_fstring(&mut bytes, 0x56, "++UE4+Release-4.27");
    assert_eq!(branch_end, 0x6d);
    put_u32(&mut bytes, branch_end, 3);
    put_u32(&mut bytes, branch_end + 4, 55);
    let entries = branch_end + 8;
    for (index, (guid, version)) in PC_CUSTOM_VERSIONS.iter().enumerate() {
        let offset = entries + index * 20;
        bytes[offset..offset + 16].copy_from_slice(guid);
        put_u32(&mut bytes, offset + 16, *version);
    }
    let end = put_utf8_fstring(&mut bytes, 0x4c1, "SaveObject");
    assert_eq!(end, 0x4d0);
    update_hash(&mut bytes);
    bytes
}

pub fn update_hash(bytes: &mut [u8]) {
    let digest = Sha1::digest(&bytes[0x40..]);
    bytes[..20].copy_from_slice(&digest);
}

fn put_u16(bytes: &mut [u8], offset: usize, value: u16) {
    bytes[offset..offset + 2].copy_from_slice(&value.to_le_bytes());
}

fn put_u32(bytes: &mut [u8], offset: usize, value: u32) {
    bytes[offset..offset + 4].copy_from_slice(&value.to_le_bytes());
}

fn put_utf8_fstring(bytes: &mut [u8], offset: usize, value: &str) -> usize {
    let length = value.len() + 1;
    put_u32(bytes, offset, u32::try_from(length).unwrap_or(0));
    let start = offset + 4;
    bytes[start..start + value.len()].copy_from_slice(value.as_bytes());
    bytes[start + value.len()] = 0;
    start + length
}
